@app.get("/tickets/{ticket_id}")
def get_ticket(ticket_id: int):
    with get_connection() as conn:
        row = execute_query(
            conn,
            "SELECT * FROM tickets WHERE id = ?",
            (ticket_id,)
        ).fetchone()

    if row is None:
        raise HTTPException(
            status_code=404,
            detail="Ticket not found"
        )

    return dict(row)


