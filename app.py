@app.middleware("http")
async def protect_demo(request: Request, call_next):
    demo_key = os.getenv("DEMO_ACCESS_KEY")
    production = os.getenv("APP_ENV", "development").lower() == "production"

    # Production must have an access key
    if production and not demo_key:
        return JSONResponse(
            status_code=503,
            content={"detail": "Demo access protection is not configured"}
        )

    # Allow local development without a key
    if not demo_key:
        return await call_next(request)

    # Public frontend and health endpoints
    if (
        request.url.path == "/"
        or request.url.path.startswith("/assets/")
        or request.url.path in ("/health", "/api/health")
    ):
        return await call_next(request)

    # Validate the demo access key
    provided_key = request.headers.get("X-Demo-Key")

    if not secrets.compare_digest(provided_key or "", demo_key):
        return JSONResponse(
            status_code=401,
            content={"detail": "Demo access key required"}
        )

    return await call_next(request)


