# SAVE AI ANALYSIS
# -----------------------------------

def save_analysis(ticket_id: int, analysis: TicketAnalysis):
    with get_connection() as conn:
        cursor = execute_query(
            conn,
            """
            INSERT INTO ticket_analyses (
                ticket_id,
                category,
                priority,
                possible_cause,
                suggested_action,
                analyzed_at,
                sources
            )
            VALUES (?, ?, ?, ?, ?, ?, ?)
            RETURNING id
            """,
            (
                ticket_id,
                analysis.category,
                analysis.priority,
                analysis.possible_cause,
                analysis.suggested_action,
                datetime.now(timezone.utc).isoformat(),
                json.dumps(
                    analysis.sources,
                    ensure_ascii=False
                )
            )
        )

        analysis_id = cursor.fetchone()["id"]

    return analysis_id


