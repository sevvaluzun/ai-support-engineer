def get_connection():
    if get_database_type() == "postgresql":
        return database_connection()

    # Keep DB_PATH accessible for existing pytest tests
    os.makedirs(os.path.dirname(DB_PATH) or ".", exist_ok=True)

    conn = sqlite3.connect(DB_PATH, timeout=10)
    conn.row_factory = sqlite3.Row

    return conn


# -----------------------------------
# DATABASE INITIALIZATION
# -----------------------------------


def initialize_database():
    database_type = get_database_type()

    with get_connection() as conn:

        # -----------------------------------
        # POSTGRESQL (NEON)
        # -----------------------------------
        if database_type == "postgresql":

            conn.execute("""
                CREATE TABLE IF NOT EXISTS tickets (
                    id INTEGER GENERATED BY DEFAULT
                        AS IDENTITY PRIMARY KEY,
                    customer TEXT NOT NULL,
                    subject TEXT NOT NULL,
                    description TEXT NOT NULL,
                    status TEXT NOT NULL DEFAULT 'open',
                    created_at TEXT NOT NULL
                )
            """)

            conn.execute("""
                CREATE TABLE IF NOT EXISTS ticket_analyses (
                    id INTEGER GENERATED BY DEFAULT
                        AS IDENTITY PRIMARY KEY,
                    ticket_id INTEGER NOT NULL,
                    category TEXT NOT NULL,
                    priority TEXT NOT NULL,
                    possible_cause TEXT NOT NULL,
                    suggested_action TEXT NOT NULL,
                    analyzed_at TEXT NOT NULL,
                    sources TEXT NOT NULL DEFAULT '[]',
                    FOREIGN KEY (ticket_id)
                        REFERENCES tickets(id)
                )
            """)

            conn.execute("""
                ALTER TABLE ticket_analyses
                ADD COLUMN IF NOT EXISTS
                sources TEXT NOT NULL DEFAULT '[]'
            """)

            # Daily AI usage tracking
            conn.execute("""
                CREATE TABLE IF NOT EXISTS ai_daily_usage (
                    usage_date TEXT PRIMARY KEY,
                    request_count INTEGER NOT NULL DEFAULT 0
                )
            """)

        # -----------------------------------
        # SQLITE (LOCAL DEVELOPMENT)
        # -----------------------------------
        else:

            conn.execute("""
                CREATE TABLE IF NOT EXISTS tickets (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    customer TEXT NOT NULL,
                    subject TEXT NOT NULL,
                    description TEXT NOT NULL,
                    status TEXT NOT NULL DEFAULT 'open',
                    created_at TEXT NOT NULL
                )
            """)

            conn.execute("""
                CREATE TABLE IF NOT EXISTS ticket_analyses (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    ticket_id INTEGER NOT NULL,
                    category TEXT NOT NULL,
                    priority TEXT NOT NULL,
                    possible_cause TEXT NOT NULL,
                    suggested_action TEXT NOT NULL,
                    analyzed_at TEXT NOT NULL,
                    sources TEXT NOT NULL DEFAULT '[]',
                    FOREIGN KEY (ticket_id)
                        REFERENCES tickets(id)
                )
            """)

            columns = conn.execute(
                "PRAGMA table_info(ticket_analyses)"
            ).fetchall()

            column_names = [
                column["name"] for column in columns
            ]

            if "sources" not in column_names:
                conn.execute("""
                    ALTER TABLE ticket_analyses
                    ADD COLUMN sources
                    TEXT NOT NULL DEFAULT '[]'
                """)

# -----------------------------------
# DAILY AI REQUEST LIMIT
# -----------------------------------

DAILY_AI_LIMIT = 10


def consume_ai_quota():
    """
    Reserve one AI request for the current UTC day.
    Shared across all demo users.
    """
    today = datetime.now(timezone.utc).date().isoformat()

    if get_database_type() != "postgresql":
        # Local SQLite development is not rate-limited yet.
        return

    with get_connection() as conn:
        row = conn.execute(
            """
            INSERT INTO ai_daily_usage (
                usage_date,
                request_count
            )
            VALUES (%s, 1)
            ON CONFLICT (usage_date)
            DO UPDATE SET
                request_count = ai_daily_usage.request_count + 1
            WHERE ai_daily_usage.request_count < %s
            RETURNING request_count
            """,
            (today, DAILY_AI_LIMIT)
        ).fetchone()

        if row is None:
            raise HTTPException(
                status_code=429,
                detail="Daily AI investigation limit reached. Try again tomorrow."
            )



