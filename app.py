@app.post(
    "/tickets/{ticket_id}/analyze",
    response_model=TicketAnalysis
)
def analyze_existing_ticket(ticket_id: int):
    ticket = get_ticket(ticket_id)

    consume_ai_quota()

    try:
        analysis = analyze_ticket(
            subject=ticket["subject"],
            description=ticket["description"]
        )
    except Exception:
        logger.exception("AI analysis failed")
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail="AI analysis is temporarily unavailable"
        )

    save_analysis(ticket_id, analysis)

    return analysis


# -----------------------------------
# GET ANALYSIS HISTORY
# -----------------------------------

@app.get("/tickets/{ticket_id}/analyses")
def get_ticket_analyses(ticket_id: int):
    get_ticket(ticket_id)

    with get_connection() as conn:
        rows = execute_query(
            conn,
            """
            SELECT *
            FROM ticket_analyses
            WHERE ticket_id = ?
            ORDER BY id DESC
            """,
            (ticket_id,)
        ).fetchall()

    analyses = []

    for row in rows:
        analysis = dict(row)
        analysis["sources"] = json.loads(
            analysis["sources"]
        )
        analyses.append(analysis)

    return analyses


